/** A `StringKey`'s text with `{placeholders}` filled; the key itself when no row has it. */
export class Strings {
  private readonly content: Readonly<Record<string, string>>;

  constructor(registry?: Registry) {
    this.content =
      registry !== undefined && registry.hasDerived('strings')
        ? registry.derived<Readonly<Record<string, string>>>('strings')
        : {};
  }

  has(key: string): boolean {
    return this.content[key] !== undefined || UI_STRINGS[key] !== undefined;
  }

  get(key: string, params: Readonly<Record<string, string | number>> = {}): string {
    const raw = this.content[key] ?? UI_STRINGS[key] ?? key;
    return fill(raw, params);
  }

  /** Every template whose key starts with `prefix`, the content's over the UI table's (T-720: the legend reads a line's key back from its text). */
  templates(prefix: string): [string, string][] {
    const out = new Map<string, string>();
    for (const [key, value] of Object.entries(UI_STRINGS)) if (key.startsWith(prefix)) out.set(key, value);
    for (const [key, value] of Object.entries(this.content)) if (key.startsWith(prefix)) out.set(key, value);
    return [...out];
  }
}

/**
 * `"{dwarf} has found {material}."` with the named values; unknown placeholders stay.
 * Plural forms `{count|singular|plural}` format as count and chosen noun (e.g. `{n|table|tables}`
 * yields "1 table" or "4 tables"; `!` prefix on singular yields only the noun).
 */
export function fill(template: string, params: Readonly<Record<string, string | number>>): string {
  return template.replace(/\{(\w+)(?:\|([^|}]+)\|([^|}]+))?\}/g, (whole, name: string, singular?: string, plural?: string) => {
    const value = params[name];
    if (value === undefined) return whole;
    if (singular !== undefined && plural !== undefined) {
      const isOne = Number(value) === 1;
      const form = isOne ? singular : plural;
      if (form.startsWith('!')) return form.slice(1);
      if (form.includes('#')) return form.replace(/#/g, String(value));
      return `${value} ${form}`;
    }
    return String(value);
  });
}
