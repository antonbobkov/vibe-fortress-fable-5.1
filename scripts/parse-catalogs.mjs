#!/usr/bin/env node
// Parses docs/04-implementation/event-catalog.md and command-catalog.md, and regenerates
// src/core/event-types.ts and src/core/command-types.ts from them.
//
// T-M0-07: "generate `src/core/event-types.ts` and `command-types.ts` from the catalogs with a
// script, or hand-write and test against the catalog's parsed list". Both: the script writes them
// and `test/unit/catalogs.test.ts` compares the committed files against a fresh parse.
//
// Usage: node scripts/parse-catalogs.mjs [--write]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { splitRow } from './lib/md-tables.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const EVENT_DOC = join(root, 'docs/04-implementation/event-catalog.md');
export const COMMAND_DOC = join(root, 'docs/04-implementation/command-catalog.md');

function tableRows(text) {
  const out = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.startsWith('|')) continue;
    const cells = splitRow(line);
    if (cells.every((c) => /^:?-+:?$/.test(c))) continue;
    if (!cells[0]?.includes('`')) continue;
    out.push(cells);
  }
  return out;
}

function ticked(cell) {
  return Array.from(String(cell ?? '').matchAll(/`([^`]+)`/g)).map((m) => m[1]);
}

/** @returns {{ name: string, fields: string, emitters: string, subscribers: string }[]} */
export function parseEvents(docPath = EVENT_DOC) {
  const text = readFileSync(docPath, 'utf8');
  const out = [];
  const seen = new Set();
  for (const cells of tableRows(text)) {
    for (const name of ticked(cells[0])) {
      if (!/^[A-Z][A-Za-z]+$/.test(name)) continue;
      if (seen.has(name)) throw new Error(`event-catalog.md: duplicate event ${name}`);
      seen.add(name);
      out.push({
        name,
        fields: (cells[1] ?? '').replace(/`/g, ''),
        emitters: cells[2] ?? '',
        subscribers: cells[3] ?? '',
      });
    }
  }
  if (out.length === 0) throw new Error('event-catalog.md: no events parsed');
  return out;
}

/** @returns {{ name: string, fields: string, owner: string }[]} */
export function parseCommands(docPath = COMMAND_DOC) {
  const text = readFileSync(docPath, 'utf8');
  const out = [];
  const seen = new Set();
  for (const cells of tableRows(text)) {
    const owner = (cells[2] ?? '').trim();
    if (owner === '' || owner === 'Owner') continue;
    for (const name of ticked(cells[0])) {
      if (!/^[A-Z][A-Za-z]+$/.test(name)) continue;
      if (seen.has(name)) throw new Error(`command-catalog.md: duplicate command ${name}`);
      seen.add(name);
      out.push({ name, fields: (cells[1] ?? '').replace(/`/g, ''), owner });
    }
  }
  if (out.length === 0) throw new Error('command-catalog.md: no commands parsed');
  return out;
}

/** The app-level commands named in the prose after the table. */
export function parseAppCommands(docPath = COMMAND_DOC) {
  const text = readFileSync(docPath, 'utf8');
  const m = /App-level \(not simulation commands, not logged\):([\s\S]*?)\n\n/.exec(text);
  if (m === null) throw new Error('command-catalog.md: no app-level command paragraph');
  return Array.from(new Set(ticked(m[1]))).filter((n) => /^[A-Z][A-Za-z]+$/.test(n));
}

export function parseRejectReasons(docPath = COMMAND_DOC) {
  const text = readFileSync(docPath, 'utf8');
  const m = /## Rejection reasons\s*\n\s*([\s\S]*?)\.\s*\n/.exec(text);
  if (m === null) throw new Error('command-catalog.md: no rejection reason list');
  return ticked(m[1]);
}

// ---------- generation ----------

const HEADER = (doc) =>
  `// GENERATED by scripts/parse-catalogs.mjs from docs/04-implementation/${doc}.\n` +
  `// Do not edit by hand; edit the catalog and re-run \`node scripts/parse-catalogs.mjs --write\`.\n` +
  `// test/unit/catalogs.test.ts fails if this file and the catalog disagree.\n\n`;

function quoteList(names, indent = '  ') {
  return names.map((n) => `${indent}'${n}',`).join('\n');
}

export function eventTypesSource() {
  const events = parseEvents();
  return (
    HEADER('event-catalog.md') +
    `/** Every event type in the catalog, in document order. */\n` +
    `export const EVENT_TYPES = [\n${quoteList(events.map((e) => e.name))}\n] as const;\n\n` +
    `export type EventType = (typeof EVENT_TYPES)[number];\n\n` +
    `/** The documented field list of each event, for the debug panel and the tests. */\n` +
    `export const EVENT_FIELDS: Readonly<Record<EventType, string>> = Object.freeze({\n` +
    events.map((e) => `  ${e.name}: ${JSON.stringify(e.fields)},`).join('\n') +
    `\n});\n\n` +
    `const EVENT_TYPE_SET: ReadonlySet<string> = new Set<string>(EVENT_TYPES);\n\n` +
    `export function isEventType(value: string): value is EventType {\n` +
    `  return EVENT_TYPE_SET.has(value);\n}\n`
  );
}

export function commandTypesSource() {
  const commands = parseCommands();
  const app = parseAppCommands();
  const reasons = parseRejectReasons();
  return (
    HEADER('command-catalog.md') +
    `/** Every simulation command in the catalog, in document order. */\n` +
    `export const COMMAND_TYPES = [\n${quoteList(commands.map((c) => c.name))}\n] as const;\n\n` +
    `export type CommandType = (typeof COMMAND_TYPES)[number];\n\n` +
    `/** App-level commands: not simulation commands and not logged. */\n` +
    `export const APP_COMMAND_TYPES = [\n${quoteList(app)}\n] as const;\n\n` +
    `export type AppCommandType = (typeof APP_COMMAND_TYPES)[number];\n\n` +
    `/** The owning system of every command; the core routes by this table. */\n` +
    `export const COMMAND_OWNERS: Readonly<Record<CommandType, string>> = Object.freeze({\n` +
    commands.map((c) => `  ${c.name}: '${c.owner}',`).join('\n') +
    `\n});\n\n` +
    `/** The documented field list of each command. */\n` +
    `export const COMMAND_FIELDS: Readonly<Record<CommandType, string>> = Object.freeze({\n` +
    commands.map((c) => `  ${c.name}: ${JSON.stringify(c.fields)},`).join('\n') +
    `\n});\n\n` +
    `/** The fixed rejection reasons of command-catalog.md § Rejection reasons. */\n` +
    `export const REJECT_REASONS = [\n${quoteList(reasons)}\n] as const;\n\n` +
    `export type RejectReason = (typeof REJECT_REASONS)[number];\n\n` +
    `const COMMAND_TYPE_SET: ReadonlySet<string> = new Set<string>(COMMAND_TYPES);\n\n` +
    `export function isCommandType(value: string): value is CommandType {\n` +
    `  return COMMAND_TYPE_SET.has(value);\n}\n\n` +
    `/** The strings-table key the UI shows for a rejection. */\n` +
    `export function rejectStringKey(reason: RejectReason): string {\n` +
    `  return \`reject.\${reason}\`;\n}\n`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const write = process.argv.includes('--write');
  const targets = [
    [join(root, 'src/core/event-types.ts'), eventTypesSource()],
    [join(root, 'src/core/command-types.ts'), commandTypesSource()],
  ];
  for (const [file, source] of targets) {
    if (write) {
      writeFileSync(file, source, 'utf8');
      console.log(`wrote ${file}`);
    } else {
      console.log(`${file}: ${source.split('\n').length} lines (use --write to write)`);
    }
  }
  console.log(`${parseEvents().length} events, ${parseCommands().length} commands, ${parseRejectReasons().length} reject reasons`);
}
